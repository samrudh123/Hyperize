#!/bin/bash
# Generate progress.css — the progress line under custom/now-playing.
#
# GTK CSS has no attr()/var(), so a width can't come from data. now-playing.py
# tags the label p0..p100 instead and each class here sets the width of the
# 2px line along the module's bottom edge: first layer the elapsed part in the
# player's own colour (currentColor, so it follows spotify green / paused grey
# / …), second layer the full-width dim track. Re-run after changing a value.
out="$(dirname "$0")/progress.css"
{
    echo "/* Generated by gen-progress-css.sh — edit that, not this. */"
    echo "#custom-now-playing {"
    echo "  background-image: linear-gradient(currentColor, currentColor),"
    echo "                    linear-gradient(alpha(@surface1, 0.9), alpha(@surface1, 0.9));"
    echo "  background-repeat: no-repeat;"
    echo "  background-position: left bottom, left bottom;"
    echo "  background-size: 0% 2px, 0% 2px;   /* no p-class (no length known): no line */"
    echo "}"
    for i in $(seq 0 100); do
        echo "#custom-now-playing.p$i { background-size: $i% 2px, 100% 2px; }"
    done
} > "$out"
