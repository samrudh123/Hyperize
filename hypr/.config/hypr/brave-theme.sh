#!/bin/bash
# Generate a Brave/Chromium theme extension in Catppuccin Mocha + the current
# desktop accent.
#
#   brave-theme.sh          build at the accent in theme/accent
#   brave-theme.sh <hex>    build at an explicit colour
#
# WHY THIS IS A SEPARATE SCRIPT AND NOT A MANIFEST ENTRY
#
# set-accent.sh renders by substituting a token with SIX HEX DIGITS. Chromium
# theme manifests do not take hex — every colour is a JSON array of decimal
# channels, `[137, 180, 250]`. A sed-based render cannot produce that, so
# Brave cannot ride the normal template mechanism without teaching the
# renderer a second output format. It is generated here instead, and the
# desktop accent does NOT drag it along: after SUPER+ALT+C, re-run this
# script and reload the extension by hand.
#
# WHERE THE OUTPUT LIVES
#
# Under the snap this had to sit in ~/snap/brave/common: strict confinement
# gave Brave access to NON-HIDDEN files in $HOME only, so an extension under
# ~/.config/hypr/ was literally unreadable and "Load unpacked" failed with a
# file-not-found. The deb runs unconfined, so that constraint is gone and the
# theme now lives with the rest of the theming.
#
# NOTE: the old ~/snap/brave/common path was DELETED with the snap, which also
# broke the already-loaded extension in Brave. After running this you must
# re-add it via Load unpacked — the entry pointing at the old path is dead and
# should be removed.

set -u

OUT="$HOME/.config/hypr/theme/brave-theme"
ACCENT_FILE="$HOME/.config/hypr/theme/accent"
ORIGINAL="cba6f7"

hex="${1:-}"
if [ -z "$hex" ]; then
    hex="$ORIGINAL"
    [ -s "$ACCENT_FILE" ] && IFS= read -r hex < "$ACCENT_FILE"
fi
hex="$(printf '%s' "${hex#\#}" | tr 'A-Z' 'a-z')"
[[ "$hex" =~ ^[0-9a-f]{6}$ ]] || { echo "bad colour: $hex" >&2; exit 1; }

# hex -> "r, g, b"
rgb() {
    local h="${1#\#}"
    printf '%d, %d, %d' "0x${h:0:2}" "0x${h:2:2}" "0x${h:4:2}"
}

mkdir -p "$OUT"
cat > "$OUT/manifest.json" <<JSON
{
  "manifest_version": 3,
  "name": "Catppuccin Mocha (desktop accent)",
  "version": "1.0",
  "description": "Generated by ~/.config/hypr/brave-theme.sh at accent #$hex.",
  "theme": {
    "colors": {
      "frame":                    [$(rgb 11111b)],
      "frame_inactive":           [$(rgb 11111b)],
      "frame_incognito":          [$(rgb 181825)],
      "frame_incognito_inactive": [$(rgb 181825)],

      "toolbar":                  [$(rgb 1e1e2e)],
      "tab_text":                 [$(rgb cdd6f4)],
      "tab_background_text":      [$(rgb a6adc8)],
      "bookmark_text":            [$(rgb cdd6f4)],

      "omnibox_background":       [$(rgb 313244)],
      "omnibox_text":             [$(rgb cdd6f4)],

      "ntp_background":           [$(rgb 1e1e2e)],
      "ntp_text":                 [$(rgb cdd6f4)],
      "ntp_link":                 [$(rgb $hex)],

      "button_background":        [$(rgb 313244)],
      "toolbar_button_icon":      [$(rgb $hex)]
    },
    "tints": {
      "frame":            [-1, -1, -1],
      "frame_inactive":   [-1, -1, -1],
      "background_tab":   [-1, -1, -1]
    },
    "properties": {
      "ntp_logo_alternate": 1
    }
  }
}
JSON

echo "wrote $OUT/manifest.json at accent #$hex"
echo
echo "Load it once (it persists after that):"
echo "  1. brave://extensions  ->  enable Developer mode (top right)"
echo "  2. Load unpacked  ->  $OUT"
echo
echo "After a SUPER+ALT+C accent change: re-run this script, then press the"
echo "reload arrow on the extension card. Brave caches theme manifests, so"
echo "regenerating alone does not repaint it."
