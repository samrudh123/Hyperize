#!/bin/bash
# KDE apps' colour scheme — Catppuccin Mocha with the desktop accent.
#
#   kde-theme.sh [hex]     hex defaults to the saved accent (theme/accent)
#
# Writes ~/.local/share/color-schemes/CatppuccinMochaRice.colors, a KDE colour
# scheme, and applies it two ways:
#   * Kdenlive: ~/.config/kdenliverc points at it (Kdenlive manages its own
#     scheme and ignores kdeglobals).
#   * every other KDE app (KDE Connect, …): its colour groups are merged into
#     ~/.config/kdeglobals, which KColorScheme / Kirigami read directly — no
#     Plasma or platform-theme plugin needed. Other kdeglobals groups (file
#     dialog settings etc.) are left as they are. [Icons] Theme=Papirus-Mocha,
#     the icon theme GTK and fuzzel use, so KDE icons aren't black on the dark
#     background and folders are in the accent. Since plasma-integration is
#     installed and hyprland.conf sets QT_QPA_PLATFORMTHEME=kde, EVERY Qt app
#     reads all of this (colours, Breeze style, icons) through KDE's platform
#     theme, not just the KColorScheme-aware ones.
# Called by app-accent.sh on every accent change (SUPER+ALT+C). KDE apps read
# it at startup, so open ones pick a new accent up on their next launch.
# (Was kdenlive-theme.sh.)
#
# Not a set-accent.sh template: the .colors format wants the accent as
# decimal "r,g,b" (and a dimmed variant of it), not as a hex token, so the
# file is generated whole instead. It is fully derived — edit THIS script,
# not the .colors file.

set -u

hex="${1:-$(cat "$HOME/.config/hypr/theme/accent" 2>/dev/null)}"
hex="${hex#\#}"; hex="${hex,,}"
[[ "$hex" =~ ^[0-9a-f]{6}$ ]] || hex="89b4fa"

NAME="CatppuccinMochaRice"
OUT="$HOME/.local/share/color-schemes/$NAME.colors"
RC="$HOME/.config/kdenliverc"

rgb() { printf '%d,%d,%d' "0x${1:0:2}" "0x${1:2:2}" "0x${1:4:2}"; }

# $1 blended into $2 at $3 percent of $1 — the dimmed selection colour.
mix() {
    local a="$1" b="$2" p="$3" i out=""
    for i in 0 2 4; do
        out+=$(printf '%02x' $(( (0x${a:i:2} * p + 0x${b:i:2} * (100 - p)) / 100 )))
    done
    printf '%s' "$out"
}

# Catppuccin Mocha
base=$(rgb 1e1e2e);     mantle=$(rgb 181825);   crust=$(rgb 11111b)
surface0=$(rgb 313244); surface1=$(rgb 45475a); overlay0=$(rgb 6c7086)
text=$(rgb cdd6f4);     subtext0=$(rgb a6adc8)
red=$(rgb f38ba8);      peach=$(rgb fab387);    yellow=$(rgb f9e2af)
green=$(rgb a6e3a1);    mauve=$(rgb cba6f7)
# THEMES: the scheme is written in Mocha below and recoloured into the current
# theme (rice-theme.py subst) right after; the dimmed accent mixes toward the
# theme's own base.
RICE="$HOME/.config/hypr/rice-theme.py"
tbase=$(/usr/bin/python3 -c 'import json,sys; print(json.load(open(sys.argv[1]))["base"].lstrip("#"))' \
        "$HOME/.config/hypr/theme/palette.json" 2>/dev/null || echo 1e1e2e)
accent=$(rgb "$hex");   accentdim=$(rgb "$(mix "$hex" "$tbase" 45)")

# Foreground roles shared by every colour set.
fg() {
    cat <<EOF
ForegroundActive=$peach
ForegroundInactive=$subtext0
ForegroundLink=$accent
ForegroundNegative=$red
ForegroundNeutral=$yellow
ForegroundNormal=$text
ForegroundPositive=$green
ForegroundVisited=$mauve
DecorationFocus=$accent
DecorationHover=$accent
EOF
}

mkdir -p "$(dirname "$OUT")"
cat > "$OUT" <<EOF
# Generated by ~/.config/hypr/kde-theme.sh — accent #$hex.
# Overwritten on every accent change; edit the script instead.

[ColorEffects:Disabled]
Color=$base
ColorAmount=0.3
ColorEffect=2
ContrastAmount=0.1
ContrastEffect=0
IntensityAmount=-1
IntensityEffect=0

[ColorEffects:Inactive]
ChangeSelectionColor=false
Enable=false

[Colors:Button]
BackgroundNormal=$surface0
BackgroundAlternate=$surface1
$(fg)

[Colors:Complementary]
BackgroundNormal=$crust
BackgroundAlternate=$mantle
$(fg)

[Colors:Header]
BackgroundNormal=$crust
BackgroundAlternate=$mantle
$(fg)

[Colors:Header][Inactive]
BackgroundNormal=$crust
BackgroundAlternate=$mantle
$(fg)

[Colors:Selection]
BackgroundNormal=$accent
BackgroundAlternate=$accentdim
ForegroundActive=$crust
ForegroundInactive=$surface0
ForegroundLink=$crust
ForegroundNegative=$crust
ForegroundNeutral=$crust
ForegroundNormal=$crust
ForegroundPositive=$crust
ForegroundVisited=$crust
DecorationFocus=$accent
DecorationHover=$accent

[Colors:Tooltip]
BackgroundNormal=$crust
BackgroundAlternate=$mantle
$(fg)

[Colors:View]
BackgroundNormal=$base
BackgroundAlternate=$mantle
$(fg)

[Colors:Window]
BackgroundNormal=$mantle
BackgroundAlternate=$crust
$(fg)

[General]
ColorScheme=$NAME
Name=Catppuccin Mocha (Rice)
shadeSortColumn=true

[KDE]
contrast=4
widgetStyle=Breeze

[WM]
activeBackground=$crust
activeBlend=$text
activeForeground=$text
inactiveBackground=$crust
inactiveBlend=$overlay0
inactiveForeground=$overlay0
EOF

# Select it in Kdenlive (same two keys its Color Theme menu writes).
/usr/bin/python3 "$RICE" subst-file "$OUT"

if command -v kwriteconfig6 >/dev/null; then
    kwriteconfig6 --file "$RC" --group UiSettings --key ColorScheme "$NAME"
    kwriteconfig6 --file "$RC" --group UiSettings --key ColorSchemePath "$NAME.colors"
fi

# Everything else KDE: merge the scheme's colour groups into kdeglobals.
/usr/bin/python3 - "$OUT" "$HOME/.config/kdeglobals" <<'PY'
import configparser, os, sys

def load(path):
    c = configparser.ConfigParser(interpolation=None, strict=False, delimiters=("=",))
    c.optionxform = str                  # KDE keys are case-sensitive
    c.read(path)
    return c

scheme, dest = load(sys.argv[1]), load(sys.argv[2])
ours = lambda sec: sec.startswith(("Colors:", "ColorEffects:")) or sec in ("WM", "KDE")
for sec in [s for s in dest.sections() if ours(s)]:
    dest.remove_section(sec)             # stale groups from an older scheme
for sec in filter(ours, scheme.sections()):
    dest[sec] = dict(scheme[sec])
for sec, key, val in (("General", "ColorScheme", scheme["General"]["ColorScheme"]),
                      ("Icons", "Theme", "Papirus-Mocha")):
    if not dest.has_section(sec):
        dest.add_section(sec)
    dest[sec][key] = val
tmp = sys.argv[2] + ".tmp"
with open(tmp, "w") as f:
    dest.write(f, space_around_delimiters=False)
os.replace(tmp, sys.argv[2])
PY
