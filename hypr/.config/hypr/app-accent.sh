#!/bin/bash
# Carry the desktop accent into the Catppuccin-themed apps — called by
# set-accent.sh on commit and on --restore (login / picker Escape).
#
#   app-accent.sh <hex>
#
# These apps cannot use set-accent.sh's template trick (swap one hex token),
# because two of them take an accent NAME, not a hex:
#
#   Discord (Vesktop)  Vencord QuickCSS @imports catppuccin-mocha-<name>.theme.css
#                      — Vencord watches quickCss.css, so this is live.
#   Spotify            spicetify Themes/catppuccin/color.ini [mocha]: button +
#                      button-active (play buttons, progress bar, toggles) set
#                      to the hex. Needs `spicetify refresh` + a Spotify restart.
#   YouTube Music      --ctp-accent in its theme CSS, set to the hex. Read at
#                      app start, so it needs a restart too.
#   KDE apps           KDE colour scheme generated by kde-theme.sh (Kdenlive,
#                      KDE Connect, …). Read at app start; never restarted
#                      (Kdenlive could lose an unsaved edit).
#   GTK3 apps          gtk-theme switched to catppuccin-mocha-<name>; live.
#   GNOME Settings     Appearance accent set to the nearest of GNOME's nine.
#   LibreOffice        Catppuccin colour scheme for <name> (libreoffice-theme.sh);
#                      next start (deferred until it closes if open).
#   Folder icons       Papirus-Mocha's folders re-pointed at the nearest Mocha
#                      accent by folder-accent.sh; live (icon theme flip).
#
# A custom (non-palette) hex is mapped to the NEAREST Catppuccin Mocha accent
# for the name-based ones (Discord), and used exactly where a hex is accepted.
#
# Spotify / YouTube Music are restarted only if they are running and NOT
# playing; otherwise they pick the colour up next launch. Nothing happens at
# all when the accent hasn't changed since the last run (state file below), so
# --restore at login and Escape in the picker cost nothing.

set -u

hex="${1#\#}"; hex="${hex,,}"
[[ "$hex" =~ ^[0-9a-f]{6}$ ]] || { echo "usage: app-accent.sh <hex>" >&2; exit 2; }

# THEMES (set-theme.sh): everything below is written for Catppuccin Mocha and
# passed through rice-theme.py's palette substitution for any other theme;
# "the accent's name" is its ROLE in the current theme (blue, peach, …).
RICE="$HOME/.config/hypr/rice-theme.py"
THEME_ID=$(/usr/bin/python3 "$RICE" current)
PRISTINE="$HOME/.config/hypr/theme/pristine"
mkdir -p "$PRISTINE"
# $1 = live file: keep a pristine Mocha copy the first time, then write the
# live file as that copy in the current theme's colours.
retheme() {
    local f="$1" keep
    keep="$PRISTINE/app-$(printf '%s' "$1" | md5sum | cut -c1-12)-$(basename "$1")"
    [ -f "$f" ] || return 1
    [ -f "$keep" ] || cp -a "$f" "$keep"
    /usr/bin/python3 "$RICE" subst "$THEME_ID" < "$keep" > "$f.rice-tmp" && mv -f "$f.rice-tmp" "$f"
}

STATE="$HOME/.config/hypr/theme/app-accent"
[ "$(cat "$STATE" 2>/dev/null)" = "$THEME_ID $hex" ] && [ "${2:-}" != "--force" ] && exit 0

SPICETIFY="$HOME/.spicetify/spicetify"
SPICE_INI="$HOME/.config/spicetify/Themes/catppuccin/color.ini"
YTM_CSS="$HOME/.config/YouTube Music/themes/catppuccin-mocha.css"
VESKTOP_QCSS="$HOME/.config/vesktop/settings/quickCss.css"

name=$(/usr/bin/python3 "$RICE" nearest "$hex" "$THEME_ID")

# Is this MPRIS player (playerctl name prefix) currently playing?
playing() { playerctl -l 2>/dev/null | grep -i "^$1" | while read -r p; do
    playerctl -p "$p" status 2>/dev/null; done | grep -qx Playing; }

# ── Discord (Vesktop) ──────────────────────────────────────────────────────
# Mocha: @import Catppuccin's hosted theme. Other themes: the same CSS,
# fetched once (cached in theme/discord/), recoloured and inlined.
if [ -d "$(dirname "$VESKTOP_QCSS")" ]; then
    url="https://catppuccin.github.io/discord/dist/catppuccin-mocha-$name.theme.css"
    if [ "$THEME_ID" = mocha ]; then
        cat > "$VESKTOP_QCSS" <<EOF
/* Written by ~/.config/hypr/app-accent.sh — follows the SUPER+ALT+C accent.
   Edits here are overwritten on the next accent change. */
@import url("$url");
EOF
    else
        cache="$HOME/.config/hypr/theme/discord/catppuccin-mocha-$name.theme.css"
        mkdir -p "${cache%/*}"
        if [ ! -s "$cache" ]; then
            curl -fsSL --max-time 20 "$url" -o "$cache.tmp" && [ -s "$cache.tmp" ] && mv -f "$cache.tmp" "$cache"
        fi
        if [ -s "$cache" ]; then
            { printf '/* Written by ~/.config/hypr/app-accent.sh — %s theme, %s accent.\n   Edits here are overwritten on the next change. */\n' "$THEME_ID" "$name"
              /usr/bin/python3 "$RICE" subst "$THEME_ID" < "$cache"; } > "$VESKTOP_QCSS.tmp" \
                && mv -f "$VESKTOP_QCSS.tmp" "$VESKTOP_QCSS"
        fi
    fi
fi

# ── YouTube Music ──────────────────────────────────────────────────────────
if [ -f "$YTM_CSS" ]; then
    retheme "$YTM_CSS"
    sed -i -E "s/^(\s*--ctp-accent:).*;/\1 #$hex;/" "$YTM_CSS"
    if pgrep -x youtube-music >/dev/null && ! playing YoutubeMusic; then
        pkill -x youtube-music
        for _ in $(seq 20); do pgrep -x youtube-music >/dev/null || break; sleep 0.5; done
        hyprctl dispatch exec /usr/bin/youtube-music >/dev/null
    fi
fi

# ── Spotify ────────────────────────────────────────────────────────────────
if [ -f "$SPICE_INI" ] && [ -x "$SPICETIFY" ]; then
    retheme "$SPICE_INI"     # [mocha] in the theme's colours (other flavours have other hexes)
    # Only inside [mocha]; the other flavours are left as shipped.
    sed -i -E "/^\[mocha\]/,/^\[/ s/^(button|button-active)(\s*=\s*).*/\1\2$hex/" "$SPICE_INI"
    # ...and the theme's own accent setting (Settings > Catppuccin > "Choose an
    # accent color"), which takes a NAME: theme.js applies RICE_ACCENT when it
    # changes, so the dropdown shows the desktop accent too.
    sed -i -E "s/^(  const RICE_ACCENT = )\"[a-z]+\";/\1\"$name\";/" \
        "$(dirname "$SPICE_INI")/theme.js"
    "$SPICETIFY" refresh >/dev/null 2>&1
    if pgrep -x spotify >/dev/null && ! playing spotify; then
        pkill -x spotify
        for _ in $(seq 20); do pgrep -x spotify >/dev/null || break; sleep 0.5; done
        hyprctl dispatch exec /usr/bin/spotify >/dev/null
    fi
fi

# ── KDE apps (Kdenlive, KDE Connect, …) ───────────────────────────────────
# Regenerates the KDE colour scheme + kdeglobals; read at app startup, so no
# restart here — an open Kdenlive project is never killed for a colour change.
"$HOME/.config/hypr/kde-theme.sh" "$hex"

# ── GTK3 theme (Catppuccin Mocha, one per accent) ──────────────────────────
# catppuccin/gtk v1.0.3, the 14 Mocha accents, in ~/.local/share/themes. GTK3
# apps (nm-connection-editor, blueman, the bars' own panels underneath their
# CSS, …) restyle live when gtk-theme changes. libadwaita apps ignore it —
# ~/.config/gtk-4.0/gtk.css themes those.
# (other themes: a recoloured copy, built once by rice-theme.py gtk)
gtk_theme=$(/usr/bin/python3 "$RICE" gtk "$name" "$THEME_ID")
if [ -d "$HOME/.local/share/themes/$gtk_theme" ]; then
    gsettings set org.gnome.desktop.interface gtk-theme "$gtk_theme"
    # --follow-symlinks: both files are stow links into ~/Hyperize; plain -i
    # would swap each link for a copy
    sed -i --follow-symlinks "s/^gtk-theme-name=.*/gtk-theme-name=$gtk_theme/" \
        "$HOME/.config/gtk-3.0/settings.ini" "$HOME/.config/gtk-4.0/settings.ini"
    # now, not just at the end: LibreOffice / Spotify below can take a while
    "$HOME/.config/hypr/set-accent.sh" --git-refresh >/dev/null 2>&1 &
fi

# ── LibreOffice ────────────────────────────────────────────────────────────
# Catppuccin's application-colour scheme for the nearest Mocha accent; waits
# for LibreOffice to close if it is open (it rewrites its config on exit).
"$HOME/.config/hypr/libreoffice-theme.sh" "$hex" >/dev/null

# ── GNOME accent (Settings > Appearance) ───────────────────────────────────
# GNOME offers nine fixed accents; pick the one in the same hue family, so the
# Appearance page shows the desktop's accent selected. (libadwaita apps' actual
# accent comes from ~/.config/gtk-4.0/gtk.css, which has the exact hex.)
gnome_accent=$(python3 - "$hex" <<'PYEOF'
import colorsys, sys
h = sys.argv[1]
r, g, b = (int(h[i:i+2], 16) / 255 for i in (0, 2, 4))
hue, light, sat = colorsys.rgb_to_hls(r, g, b)
deg = hue * 360
if sat < 0.12:
    print("slate")
elif deg < 15 or deg >= 340:
    # Mocha rosewater / flamingo are pale pinks, not reds
    print("pink" if light > 0.85 else "red")
else:
    for top, name in ((40, "orange"), (70, "yellow"), (160, "green"), (195, "teal"),
                      (255, "blue"), (300, "purple"), (340, "pink")):
        if deg < top:
            print(name)
            break
PYEOF
)
[ -n "$gnome_accent" ] && gsettings set org.gnome.desktop.interface accent-color "$gnome_accent"

# ── Folder icons (Papirus-Mocha) ───────────────────────────────────────────
# Catppuccin folders in the nearest Mocha accent; flips the icon theme so open
# windows (Files, the app grid, …) redraw them.
"$HOME/.config/hypr/folder-accent.sh" "$hex" >/dev/null

printf '%s %s\n' "$THEME_ID" "$hex" > "$STATE"

# The gtk-theme-name sed above (and theme ids) change file lengths, which
# git's accent filter can't hide by itself — see set-accent.sh --git-refresh.
"$HOME/.config/hypr/set-accent.sh" --git-refresh
