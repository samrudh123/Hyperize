#!/bin/bash
# Apply custom sidebar icons listed in dock-icons.conf.
#
# How the dock picks an icon: a pinned entry `X` in ~/.cache/nwg-dock-pinned is
# resolved to `X.desktop`, and the dock draws whatever that file's `Icon=` says.
# Desktop files in ~/.local/share/applications take precedence over
# /usr/share/applications, so an override there changes the icon without
# touching anything system-owned (and it is removed by deleting one file).
#
# Two kinds of entry are handled differently:
#
#   * A normal app (a system .desktop exists) -> a full copy is written to
#     ~/.local/share/applications with the new Icon= and an X-Dock-Icon=managed
#     marker. Drop the line from the conf and the next run deletes the override.
#   * A place generated by dock-places.sh (dock-trash, dock-disk-*) -> its
#     Icon= is edited in place, with no marker, because dock-places.sh owns the
#     file. Run THIS script after that one.
#
# Note the override is the standard XDG mechanism, so the new icon also applies
# in fuzzel/nwg-drawer — that is usually what you want, but it is not dock-only.

set -u

CONF="${1:-$HOME/.config/hypr/dock-icons.conf}"
USERAPPS="$HOME/.local/share/applications"
SYSDIRS=(
    /usr/local/share/applications
    /usr/share/applications
    /var/lib/snapd/desktop/applications
    /var/lib/flatpak/exports/share/applications
    "$HOME/.local/share/flatpak/exports/share/applications"
)
MARKER="X-Dock-Icon=managed"

mkdir -p "$USERAPPS"
[ -f "$CONF" ] || { echo "dock-icons: no $CONF, nothing to do"; exit 0; }

find_system_desktop() {
    for d in "${SYSDIRS[@]}"; do
        [ -f "$d/$1.desktop" ] && { printf '%s\n' "$d/$1.desktop"; return 0; }
    done
    return 1
}

set_icon() {   # file, icon — replace every Icon= (entry plus any actions)
    local f=$1 icon=$2
    /usr/bin/python3 - "$f" "$icon" <<'PY'
import re, sys
path, icon = sys.argv[1], sys.argv[2]
text = open(path).read()
text, n = re.subn(r'(?m)^Icon=.*$', 'Icon=' + icon, text)
if n == 0:   # no Icon= at all: add one to the [Desktop Entry] section
    text = re.sub(r'(?m)^(\[Desktop Entry\]\n)', r'\1Icon=' + icon + '\n', text, count=1)
open(path, 'w').write(text)
PY
}

wanted=()
applied=0
while IFS= read -r line; do
    line="${line%%#*}"                              # strip comments
    [[ "$line" =~ ^[[:space:]]*$ ]] && continue
    entry="${line%%=*}"; icon="${line#*=}"
    entry="$(printf '%s' "$entry" | xargs)"         # trim
    icon="$(printf '%s' "$icon" | xargs)"
    [ -n "$entry" ] && [ -n "$icon" ] || continue
    wanted+=("$entry")

    target="$USERAPPS/$entry.desktop"
    if src=$(find_system_desktop "$entry"); then
        cp "$src" "$target"
        set_icon "$target" "$icon"
        grep -q "^$MARKER$" "$target" || \
            sed -i "0,/^\[Desktop Entry\]$/s//[Desktop Entry]\n$MARKER/" "$target"
        echo "  $entry -> $icon   (override of $src)"
    elif [ -f "$target" ]; then
        # generated place, or a local-only entry: edit in place, do not adopt it
        set_icon "$target" "$icon"
        echo "  $entry -> $icon   (edited $target in place)"
    else
        echo "  $entry -> SKIPPED: no $entry.desktop found anywhere" >&2
        continue
    fi
    applied=$((applied+1))
done < "$CONF"

# Drop managed overrides that are no longer requested.
shopt -s nullglob
for f in "$USERAPPS"/*.desktop; do
    grep -q "^$MARKER$" "$f" || continue
    name=$(basename "$f" .desktop)
    for w in ${wanted[@]+"${wanted[@]}"}; do
        [ "$w" = "$name" ] && continue 2
    done
    rm -f "$f"
    echo "  $name -> removed (no longer in $(basename "$CONF"))"
done

echo "dock-icons: $applied icon(s) applied"
