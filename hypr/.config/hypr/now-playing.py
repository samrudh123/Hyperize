#!/usr/bin/env python3
"""Now playing — the bottom bar's player, with a thin progress line under it.

    custom/now-playing in ~/.config/waybar/bottom.jsonc

Replaces waybar's built-in mpris module (and the phone-only phone-media.py
that sat beside it). The built-in module could not do either of these:

  * a PROGRESS LINE. GTK CSS can't read a number, so this tags the label with
    a class p0..p100 and ~/.config/waybar/progress.css (generated by
    gen-progress-css.sh) gives each class its background-size — a 2px line
    along the bottom, in the player's own colour (currentColor) over a dim
    track. Re-rendered every second while playing.
  * COLOUR BY APP for the phone. KDE Connect relays every phone app as
    "kdeconnect.mpris_<id>", so mpris could only class them all "kdeconnect";
    the app is only in the MPRIS Identity ("YouTube Morphe - My Phone").

Spotify on another device (via the Web API, for when KDE Connect can't see
the phone) is the "kdeconnect.spotifyremote" player published by spotify-remote.py — so
it gets the same line, scroll-seek and menu as everything else.

Classes (bottom.css): spotify green · youtube dim red · firefox peach ·
zen mauve · ytmusic pink · other blue · paused grey (wins) · hidden. Shows playerctld's
ACTIVE player — the one the bar's click / prev / next act on, which
media-prefer-playing.sh keeps on a playing one. Long-running: one JSON line
per change, plus a tick per second while something plays. Stdlib only.

TWO PILLS (--scope): the bar runs this twice, `--scope local` (this laptop:
Firefox, Spotify, mpv, …) and `--scope remote` (KDE Connect's phone players
and the Spotify Web API bridge — every "kdeconnect.*" player), each with its
own line and controls, so the phone and the laptop never take each other's
place. Without --scope: all players, as before.

Spotify mirrors itself across devices (the laptop app shows the phone's song,
the phone's app the laptop's), so one copy is hidden — the pill follows where
the sound comes out. See spotify_where.py.
"""

import html
import os
import json
import queue
import signal
import subprocess
import sys
import threading
import time

import spotify_where   # same directory: which Spotify copy is only a mirror
import media_modes     # same directory: shuffle / repeat (the ⇄ ⟲ buttons)

I_SPOTIFY = "\U000F04C7"   # md-spotify
I_YOUTUBE = "\U000F05C3"   # md-youtube
I_MUSIC = "\U000F075A"     # md-music
I_PHONE = "\U000F011C"     # md-cellphone
I_PAUSE = "\U000F03E4"     # md-pause
I_FIREFOX = "\U000F0239"   # md-firefox
I_BRAVE = "\U000F059F"     # md-web
I_ZEN = "\U000F05DD"       # md-bullseye: concentric rings, like Zen's logo (no Zen glyph in the Nerd Font)
I_CHROMIUM = "\U000F02AF"  # md-google_chrome
I_DEFAULT = "\U000F0386"   # md-music_note

MAX_LEN = 60
MAX_LEN_BOTH = 38      # while the other pill is showing too
SCOPES = ("local", "remote")
HIDDEN = {"text": "", "class": "hidden", "tooltip": ""}
FROZEN_AFTER = 2.5     # s a "Playing" phone player's position may stand still
_still = {}            # (player, title) -> (position µs, since)
SEP = "\x1f"


def run(*cmd):
    r = subprocess.run(cmd, capture_output=True, text=True)
    # rstrip("\n"), not strip(): Python counts the \x1f field separator as
    # whitespace, so strip() ate trailing EMPTY fields (no URL, no artist).
    return r.stdout.rstrip("\n") if r.returncode == 0 else ""


def identity(instance):
    """A player's Identity — remembered per bus name (it doesn't change;
    render() forgets players that are gone), except the bridge's: that one
    names the device Spotify is playing on."""
    if instance in _ident:
        return _ident[instance]
    out = run("busctl", "--user", "--json=short", "get-property",
              "org.mpris.MediaPlayer2." + instance, "/org/mpris/MediaPlayer2",
              "org.mpris.MediaPlayer2", "Identity")
    try:
        ident = json.loads(out)["data"]
    except (ValueError, KeyError):
        return ""
    if instance != BRIDGE:
        _ident[instance] = ident
    return ident


_ident = {}

# One render asked `playerctl -l` up to three times and spotify_where twice
# (with a phone player showing, ~9 helper processes a second): within one
# render the answers are the same. render() clears this.
_memo = {}


def players_l():
    if "l" not in _memo:
        _memo["l"] = run("playerctl", "-l").splitlines()
    return list(_memo["l"])


def mirrors_of(players):
    key = ("hidden", tuple(players))
    if key not in _memo:
        _memo[key] = spotify_where.hidden(players)
    return _memo[key]


# Every player's status / title / artist / length / position in ONE
# `playerctl -a metadata` a render, instead of a status call, a metadata call
# and the other-pill check each (5 helper processes a render -> 2). A player
# missing from it (no metadata; a title with a newline) is asked by itself.
META = ("{{status}}", "{{title}}", "{{artist}}", "{{mpris:length}}", "{{position}}")


def meta_table():
    """{instance: [status, title, artist, length, position]}"""
    if "meta" not in _memo:
        table = {}
        out = run("playerctl", "-a", "metadata", "--format", SEP.join(("{{playerInstance}}",) + META))
        for line in out.splitlines():
            f = line.split(SEP)
            if len(f) == len(META) + 1:
                table[f[0]] = f[1:]
        _memo["meta"] = table
    return _memo["meta"]


def status_of(p):
    m = meta_table().get(p)
    return m[0] if m else run("playerctl", "-p", p, "status")


# shuffle / repeat (a busctl GetAll a render) only change along with an MPRIS
# event, and every event wakes main()'s loop, which forgets these then;
# MODES_TTL s is the safety net.
_modes = {}            # player -> ((shuffle, loop), monotonic)
MODES_TTL = 10.0


def modes_of(inst):
    hit = _modes.get(inst)
    if hit and time.monotonic() - hit[1] < MODES_TTL:
        return hit[0]
    modes = media_modes.mpris(inst)
    _modes[inst] = (modes, time.monotonic())
    return modes


# spotify-remote.py's Web API bridge. Its bus name sits under "kdeconnect." so
# kdeconnectd doesn't echo it back to the phone — check for it BEFORE the
# generic kdeconnect (= phone) rules.
BRIDGE = "kdeconnect.spotifyremote"


def superseded(inst, players):
    """KDE Connect's copy of the phone's Spotify, while spotify-remote.py's
    bridge (BRIDGE, from the Web API) is up: the bridge is always
    current, the copy can be frozen (KDE Connect over Bluetooth only reports
    on connect). Same rule in media-menu.py and media-prefer-playing.sh."""
    return (inst.startswith("kdeconnect.") and inst != BRIDGE and BRIDGE in players
            and identity(inst).lower().startswith("spotify"))


def classify_phone(ident):
    """'YouTube Music - My Phone' -> 'ytmusic'. Matches Morphe/ReVanced
    builds too, which keep "YouTube" / "YouTube Music" in their names."""
    app = ident.lower()
    if app.startswith("spotify"):
        return "spotify"
    if "youtube music" in app or "yt music" in app:
        return "ytmusic"
    if "youtube" in app:
        return "youtube"
    return "other"


def describe(inst):
    """-> (colour class, icon, tooltip name, is_phone)."""
    name = inst.split(".")[0]
    if inst == BRIDGE:                                # spotify-remote.py's bridge
        device = identity(inst).partition(" - ")[2]
        return "spotify", I_SPOTIFY, f"Spotify on {device or 'another device'}", True
    if name == "kdeconnect":
        ident = identity(inst)
        app = classify_phone(ident)
        icon = {"spotify": I_SPOTIFY, "youtube": I_YOUTUBE, "ytmusic": I_MUSIC}.get(app, I_PHONE)
        app_name, _, device = ident.partition(" - ")
        return app, icon, f"{app_name or 'Phone'} on {device or 'phone'}", True
    if name.lower().startswith("youtubemusic") or name.startswith("youtube-music"):
        return "ytmusic", I_MUSIC, "YouTube Music", False
    return {
        "spotify": ("spotify", I_SPOTIFY, "Spotify", False),
        # Zen publishes its own player as firefox.instance_* too (the name is
        # hard-coded in Gecko); its Identity says "Mozilla zen".
        "firefox": (("zen", I_ZEN, "Zen", False) if gecko_owner(inst) == "zen"
                    else ("firefox", I_FIREFOX, "Firefox", False)),
        "zen": ("zen", I_ZEN, "Zen", False),            # its per-tab players
        "brave": ("other", I_BRAVE, "Brave", False),
        "chromium": ("other", I_CHROMIUM, "Chromium", False),
    }.get(name, ("other", I_DEFAULT, name, False))


def _kdec_focus(inst):
    """Make `inst` (a phone player) KDE Connect's CURRENT player, so its
    MPRIS Position is its own.

    kdeconnect-kde bug (mprisremoteplayermediaplayer2player.cpp, 25.12):
    every phone player's Position() returns m_plugin->position() — the
    position of whichever phone player the plugin currently has selected —
    not m_parent->position(). With Spotify selected, YouTube Morphe showed
    Spotify's position. Status/title/length are per player and fine.
    Selecting is the device's mprisremote `player` property (it also asks
    the phone for that player's status). Set only when it differs. The
    hidden KDE Connect Spotify copy then shows the wrong position, which
    nothing displays. Called each render, and by media-seek.sh before it
    reads a position (`now-playing.py focus <player>`).

    Skipped while nothing can have changed since the last check (_focus).
    -> True when it switched the selection (positions read before are stale)."""
    if inst == BRIDGE:
        # The bridge (Web API) shows Spotify; it reads KDE Connect's Spotify
        # copy for position, which is only right while that copy is current.
        inst = next((p for p in players_l()
                     if p.startswith("kdeconnect.mpris_")
                     and identity(p).lower().startswith("spotify")), "")
    if not inst.startswith("kdeconnect.mpris_"):
        return
    now = time.monotonic()
    if _focus["ok"] and _focus["inst"] == inst and now - _focus["at"] < FOCUS_RECHECK:
        return
    _focus["ok"] = False
    gen = _focus["gen"]                          # a change signalled while we look
    ident = identity(inst)                       # "YouTube Morphe - My Phone"
    out = run("busctl", "--user", "--json=short", "call", "org.kde.kdeconnect",
              "/modules/kdeconnect", "org.kde.kdeconnect.daemon", "devices", "bb",
              "true", "true")
    try:
        devices = json.loads(out)["data"][0]
    except (ValueError, KeyError, IndexError):
        return
    for dev in devices:
        path = f"/modules/kdeconnect/devices/{dev}/mprisremote"
        args = ("busctl", "--user", "--json=short", "get-property", "org.kde.kdeconnect",
                path, "org.kde.kdeconnect.device.mprisremote")
        try:
            names = json.loads(run(*args, "playerList"))["data"]
            current = json.loads(run(*args, "player"))["data"]
        except (ValueError, KeyError):
            continue
        # Identity is "<player> - <device>"; device names can hold " - " too,
        # so match against the real player names rather than splitting.
        name = next((n for n in names if ident.startswith(n + " - ")), None)
        if name is None:
            continue
        if name != current:
            run("busctl", "--user", "set-property", "org.kde.kdeconnect", path,
                "org.kde.kdeconnect.device.mprisremote", "player", "s", name)
        _focus.update(inst=inst, at=now, ok=_focus["watched"] and _focus["gen"] == gen)
        return name != current


# kdec_focus's last check. KDE Connect's selected player changes only when
# someone sets it or the phone's players change, and both make the device's
# mprisremote object emit `propertiesChanged` (no args; it sends no
# org.freedesktop PropertiesChanged) — kdec_watch() then bumps gen / clears
# ok and the next render looks again. FOCUS_RECHECK s is the safety net.
# Checking every render was 3 busctl calls a second.
_focus = {"inst": None, "at": 0.0, "ok": False, "gen": 0, "watched": False}
FOCUS_RECHECK = 30.0
_focus_lock = threading.Lock()


def kdec_focus(inst):
    """_kdec_focus, one caller at a time (render + the stdin seek worker)."""
    with _focus_lock:
        return _kdec_focus(inst)


def kdec_watch():
    """Thread: follow KDE Connect's mprisremote changes for kdec_focus. If
    dbus-monitor goes, kdec_focus checks every render again."""
    cmd = ["dbus-monitor", "--session",
           "type='signal',interface='org.kde.kdeconnect.device.mprisremote',"
           "member='propertiesChanged'"]
    try:
        with subprocess.Popen(cmd, stdout=subprocess.PIPE, stderr=subprocess.DEVNULL,
                              text=True, preexec_fn=die_with_parent) as p:
            for _ in p.stdout:                   # first: its own NameAcquired = listening
                _focus["watched"] = True
                _focus["gen"] += 1
                _focus["ok"] = False
    finally:
        _focus.update(watched=False, ok=False)


def position_frozen(inst, title, status, position):
    """Safety net for phone players: one that says Playing while its
    position stands still for FROZEN_AFTER s gets no progress line rather
    than a wrong one (seen over KDE Connect's Bluetooth link, and before
    kdec_focus, when phone players borrowed each other's position)."""
    key, now = (inst, title), time.monotonic()
    if status != "Playing":
        _still.pop(key, None)
        return False
    last = _still.get(key)
    if last is None or abs(position - last[0]) > 500_000:
        _still[key] = (position, now)
        return False
    return now - last[1] >= FROZEN_AFTER


def clock(us):
    s = max(0, int(us // 1_000_000))
    return f"{s // 3600}:{s // 60 % 60:02d}:{s % 60:02d}" if s >= 3600 else f"{s // 60}:{s % 60:02d}"


# Firefox tabs: the mpris-position extension's native host
# (~/.local/share/firefox-mpris-position/host.py) publishes one player per
# YouTube tab, "firefox.tab_<id>", and names the tab you're on (the focused
# Firefox window's, else the last one you were on that has a player) here.
# Zen Browser runs the same extension: "zen.tab_<id>", zen-tabs.current.
GECKO = ("firefox", "zen")
RT_DIR = os.environ.get("XDG_RUNTIME_DIR", "/tmp")


def gecko_owner(p):
    """Which browser a player belongs to: "firefox" / "zen" / None. Zen's
    OWN player is named firefox.instance_* as well (Gecko hard-codes it);
    only its Identity ("Mozilla zen") tells them apart."""
    b = p.split(".")[0]
    if b == "firefox" and p.startswith("firefox.instance"):
        if p not in _owner:             # a bus name is one process: ask once
            _owner[p] = "zen" if "zen" in identity(p).lower() else "firefox"
        return _owner[p]
    return b if b in GECKO else None


_owner = {}


def firefox_tabs(players):
    """With per-tab players around, show only the CURRENT tab (the others
    stay in media-menu.py, where picking one switches the browser to it),
    and not the browser's own player when it is one of those YouTube tabs
    (Firefox / Zen publish just one, for the tab they last started)."""
    for b in GECKO:
        players = _gecko_tabs(players, b)
    return players


def _gecko_tabs(players, b):
    tabs = [p for p in players if p.startswith(f"{b}.tab_")]
    if not tabs:
        return players
    try:
        with open(os.path.join(RT_DIR, f"{b}-tabs.current")) as f:
            cur = f.read().strip()
    except OSError:
        cur = ""
    out = []
    for p in players:
        if p.startswith(f"{b}.tab_") and cur in tabs and p != cur:
            continue
        if ".instance" in p and gecko_owner(p) == b and "youtube.com" in run(
                "playerctl", "-p", p, "metadata", "xesam:url"):
            continue
        out.append(p)
    return out


def in_scope(inst, scope):
    """remote = another device: KDE Connect's phone players and the Web API
    bridge (all "kdeconnect.*"); local = this laptop; None = everything."""
    if scope is None:
        return True
    return inst.startswith("kdeconnect.") == (scope == "remote")


def other_scope_showing(scope):
    """Is the OTHER pill showing something (a player with a title)? Then
    this one keeps its text shorter so both fit."""
    if scope is None:
        return False
    other = SCOPES[1 - SCOPES.index(scope)]
    mirrors = mirrors_of(players_l())
    for p, (status, title, *_) in meta_table().items():
        if in_scope(p, other) and status in ("Playing", "Paused") and title \
                and p not in mirrors:
            return True
    return False


def shown_player(scope=None):
    """The player the bar shows — and so the one its buttons must act on
    (media-skip.sh, media-seek.sh: `now-playing.py current`). "" if none.
    scope: only "local" or "remote" players (see in_scope)."""
    players = players_l()
    mirrors = mirrors_of(players)
    players = [p for p in players if not superseded(p, players) and p not in mirrors]
    players = [p for p in players if in_scope(p, scope)]
    players = firefox_tabs(players)
    if not players:
        return ""
    inst = players[0]                                   # playerctld's active one
    # playerctld puts ANY player that changes in front — a phone app that
    # just paused because another took over included — and
    # media-prefer-playing.sh only rotates a playing one back ~0.5 s later.
    # Show the playing one straight away instead of flickering (measured:
    # 0.7 s of "YouTube paused" while Spotify was starting).
    if status_of(inst) != "Playing":
        inst = next((p for p in players[1:] if status_of(p) == "Playing"), inst)
    return inst


_last = {"inst": None, "out": None, "at": 0.0}   # last render that had a title
BLANK_GRACE = 3.0

# Firefox 156 keeps advancing MPRIS Position while PAUSED (measured: +1 s per
# second, PlaybackStatus "Paused", whatever the page reports). So a paused
# Firefox player's line crept forward at every redraw. Hold the position it
# had when it paused instead; a seek (Seeked signal / SIGUSR1) re-reads it
# for SEEK_SETTLE s, as Firefox only has the new one once the page reported it.
_held = {}             # player -> (title, position µs)
_live_until = [0.0]    # monotonic: don't hold before this (just seeked)
SEEK_SETTLE = 1.0


def held_position(inst, title, status, position):
    if not inst.startswith(GECKO) or status != "Paused" \
            or time.monotonic() < _live_until[0]:
        _held.pop(inst, None)
        return position
    held = _held.get(inst)
    if held is None or held[0] != title:
        _held[inst] = (title, position)
        return position
    return held[1]


def render(scope=None):
    """-> (waybar dict, is_playing)."""
    _memo.clear()
    live = set(players_l())
    for cache in (_ident, _modes):                      # gone: a new one may reuse the name
        for p in [p for p in cache if p not in live]:
            del cache[p]
    inst = shown_player(scope)
    if not inst:
        return HIDDEN, False
    switched = kdec_focus(inst)                         # or its position is another's
    meta = None if switched else meta_table().get(inst)
    if meta is None:
        meta = run("playerctl", "-p", inst, "metadata", "--format", SEP.join(META)).split(SEP)
    if len(meta) != 5 or meta[0] not in ("Playing", "Paused"):
        return HIDDEN, False
    status, title, artist, length, position = meta
    if not title:
        # YouTube Morphe between videos: ~1.3 s with no title (measured).
        # Keep showing what was there rather than a blank pill.
        if _last["inst"] == inst and time.monotonic() - _last["at"] < BLANK_GRACE:
            return _last["out"], False
    colour, icon, who, phone = describe(inst)

    now = f"{title} - {artist}" if artist else title
    limit = MAX_LEN_BOTH if other_scope_showing(scope) else MAX_LEN
    if len(now) > limit:
        now = now[:limit - 1] + "…"
    now = html.escape(now)
    tail = f"  {I_PHONE}" if phone else ""
    if status == "Playing":
        text = f"{icon}  {now}{tail}"
    else:
        text = f"{I_PAUSE}  <i>{now}</i>{tail}"

    classes = [colour, status.lower()]
    when = ""
    try:
        length, position = int(length), int(position)
    except ValueError:
        length = 0                                      # live stream / unknown
    if length > 0:
        position = held_position(inst, title, status, position)
    if length > 0 and phone and inst != BRIDGE and \
            position_frozen(inst, title, status, position):
        length = 0              # don't draw a progress line we know is wrong
    if length > 0:
        pct = max(0, min(100, round(position * 100 / length)))
        classes.append(f"p{pct}")
        when = f"\n{clock(position)} / {clock(length)}"
    shuffle, loop = media_modes.state(inst, colour == "spotify", f"{status} {title}",
                                      status == "Playing", modes=modes_of(inst))
    tooltip = (f"{who}: {title}" + (f" — {artist}" if artist else "") + when
               + "\nClick: play/pause · Right-click: players · Scroll: seek")
    out = {"text": text, "tooltip": html.escape(tooltip), "class": classes,
           # for the bar plugin (--cffi): what a click / drag on the line needs
           "_pos": max(0, position) if length > 0 else 0, "_len": max(0, length),
           "_player": inst, "_playing": status == "Playing",
           "_shuffle": shuffle, "_loop": loop}
    _last.update(inst=inst, out=out, at=time.monotonic())
    return out, status == "Playing"


def die_with_parent():
    """preexec_fn: SIGTERM this child when we die. Without it every restart
    of this script (waybar reload, a kill) left its two `playerctl -F`
    followers running — 40 had piled up, all waking on every media event."""
    import ctypes
    import signal
    ctypes.CDLL("libc.so.6", use_errno=True).prctl(1, signal.SIGTERM)   # PR_SET_PDEATHSIG


def follow(cmd, q, token=None):
    with subprocess.Popen(cmd, stdout=subprocess.PIPE, stderr=subprocess.DEVNULL,
                          text=True, preexec_fn=die_with_parent) as p:
        for _ in p.stdout:
            q.put(token)
    q.put(None)


def encode(out, cffi):
    """One output line. waybar's custom module: JSON. The bar plugin
    (waybar/modules/nowplaying.c, --cffi): fields joined by \x1f, no JSON
    parser needed in C —
      text  classes(space-separated)  tooltip(\n -> \x1e)  pos_us  len_us  player  playing(0/1)
      shuffle(1/0/"")  loop(None/Playlist/Track/"")   — "" = the player can't"""
    if not cffi:
        return json.dumps({k: v for k, v in out.items() if not k.startswith("_")},
                          ensure_ascii=False)
    cls = out.get("class") or []
    cls = cls if isinstance(cls, list) else [cls]
    return SEP.join([out.get("text", ""), " ".join(cls),
                     out.get("tooltip", "").replace("\n", "\x1e"),
                     str(int(out.get("_pos", 0))), str(int(out.get("_len", 0))),
                     out.get("_player", ""), "1" if out.get("_playing") else "0",
                     out.get("_shuffle", ""), out.get("_loop", "")])


def nudge_bars():
    """Tell every running bar copy of this script (waybar's, and the plugin's
    --cffi child) to redraw now."""
    out = run("pgrep", "-f", r"^/usr/bin/python3 .*/now-playing\.py( --cffi)?( --scope [a-z]+)?$")
    for pid in out.split():
        try:
            os.kill(int(pid), signal.SIGUSR1)
        except (ValueError, OSError):
            pass


def seek_to(player, us):
    """Absolute seek of `player` to `us` µs — the plugin's click / drag on the
    line. KDE Connect players get selected first (kdec_focus), as in
    media-seek.sh."""
    kdec_focus(player)
    run("playerctl", "-p", player, "position", f"{max(0, us) / 1e6:.3f}")
    nudge_bars()


def spotify_may_move():
    """The laptop's Spotify app is playing — here or as a mirror. The pill
    that shows it can then change (laptop <-> phone) with no MPRIS event at
    all, since spotify_where.py goes by where the sound comes out; a pill
    that is hidden meanwhile would never look again. So keep ticking."""
    return run("playerctl", "-p", "spotify", "status") == "Playing"


_seek = {"want": None}
_seek_cv = threading.Condition()


def seek_worker(q):
    """The bar's seeks ("seekto <player> <us>" on stdin), one at a time,
    latest wins: a wheel spin that outruns KDE Connect skips the targets it
    has already passed instead of queueing them. Replaces a media-seek.sh +
    Python start-up per notch; kdec_focus is usually a no-op here (the shown
    player is already selected), so a seek costs one playerctl."""
    while True:
        with _seek_cv:
            while _seek["want"] is None:
                _seek_cv.wait()
            player, us = _seek["want"]
            _seek["want"] = None
        kdec_focus(player)
        run("playerctl", "-p", player, "position", f"{max(0, us) / 1e6:.3f}")
        q.put("seek")                                   # redraw (paused: nothing else will)


def read_commands(q):
    threading.Thread(target=seek_worker, args=(q,), daemon=True).start()
    for line in sys.stdin:
        what, _, rest = line.strip().partition(" ")
        if what in ("shuffle", "repeat") and rest:
            media_modes.change_bg(what, rest)
        elif what == "seekto":
            player, _, us = rest.partition(" ")
            if player and us.lstrip("-").isdigit():
                with _seek_cv:
                    _seek["want"] = (player, int(us))
                    _seek_cv.notify()


def main(cffi=False, scope=None):
    # Exit with whoever started us (waybar's `sh -c`). When the bar restarts,
    # the old copy otherwise lingers until its next print hits the closed
    # pipe — and with nothing playing that can be never. Its playerctl
    # followers go with it (die_with_parent).
    die_with_parent()
    q = queue.Queue()
    # SIGUSR1 = "redraw now" (nudge_bars(): seekto, media-seek.sh). While
    # PAUSED nothing else wakes this loop after a seek — KDE Connect emits no
    # Seeked for a seek sent through it — so the bar kept the old time.
    import signal
    signal.signal(signal.SIGUSR1, lambda *_: q.put("seek"))
    media_modes.on_change = lambda: q.put("modes")     # a Web API read changed them
    if cffi:
        # The bar's ⇄ ⟲ clicks ("shuffle <player>" / "repeat <player>"):
        # handled here, on media_modes' warm Web API connection — a fresh
        # media_modes.py process paid Python start-up + a new TLS handshake.
        # And its seeks ("seekto <player> <us>", see seek_worker).
        threading.Thread(target=read_commands, args=(q,), daemon=True).start()
    for cmd, token in ((["playerctl", "-a", "-F", "metadata", "--format",
                         # shuffle / loop: wake on the ⇄ ⟲ buttons too
                         "{{playerInstance}} {{status}} {{title}} {{artist}} {{shuffle}} {{loop}}"],
                        None),
                       (["playerctl", "-p", "playerctld", "-F", "metadata", "--format",
                         "{{status}} {{title}}"], None),
                       # a seek: redraw now, not at the next once-a-second tick
                       (["dbus-monitor", "--session",
                         "type='signal',interface='org.mpris.MediaPlayer2.Player',member='Seeked'"],
                        "seek")):
        threading.Thread(target=follow, args=(cmd, q, token), daemon=True).start()
    if scope != "local":                                # only phone players need kdec_focus
        threading.Thread(target=kdec_watch, daemon=True).start()

    last = None
    while True:
        out, playing = render(scope)
        line = encode(out, cffi)
        if line != last:
            print(line, flush=True)
            last = line
        tokens = []
        try:
            # Playing: tick each second so the progress line moves (and a seek
            # shows up) — also while Spotify may move between the pills. Paused/nothing: just wait for the next change — or
            # for the end of a seek's settle time (held_position).
            settle = _live_until[0] - time.monotonic()
            wait = 1.0 if playing or spotify_may_move() else \
                (settle + 0.05 if settle > 0 else None)
            if wait is None and media_modes.web_shown:
                # paused phone Spotify: keep re-reading shuffle / repeat
                # from the Web API — they can change on the phone meanwhile
                wait = media_modes.TTL_PAUSED + 0.1
            tokens.append(q.get(timeout=wait))
            while True:                                 # let a burst settle
                tokens.append(q.get(timeout=0.25))
        except queue.Empty:
            pass
        if tokens:                                      # an event, not the tick:
            _modes.clear()                              # shuffle / repeat may have changed
        if "seek" in tokens:
            _live_until[0] = time.monotonic() + SEEK_SETTLE


if __name__ == "__main__":
    if sys.argv[1:2] == ["seekto"] and len(sys.argv) == 4:
        seek_to(sys.argv[2], int(sys.argv[3]))          # for the bar plugin
        sys.exit(0)
    if sys.argv[1:2] == ["current"]:                    # for media-skip.sh / media-seek.sh
        print(shown_player(sys.argv[2] if sys.argv[2:3] and sys.argv[2] in SCOPES else None))
        sys.exit(0)
    if sys.argv[1:2] == ["focus"] and len(sys.argv) == 3:
        kdec_focus(sys.argv[2])                         # for media-seek.sh
        sys.exit(0)
    scope = None
    if "--scope" in sys.argv[1:-1]:
        scope = sys.argv[sys.argv.index("--scope") + 1]
        if scope not in SCOPES:
            sys.exit(f"--scope must be one of {', '.join(SCOPES)}")
    try:
        main(cffi="--cffi" in sys.argv[1:], scope=scope)
    except (KeyboardInterrupt, BrokenPipeError):
        sys.exit(0)
